export function growthAt(scenario, year) {
  const g = SCENARIOS[scenario].growth;
  const ys = Object.keys(g).map(Number).sort((a, b) => a - b);
  if (year <= ys[0]) return g[ys[0]];
  for (let i = 1; i < ys.length; i++) {
    if (year <= ys[i]) {
      const t = (year - ys[i - 1]) / (ys[i] - ys[i - 1]);
      return g[ys[i - 1]] + (g[ys[i]] - g[ys[i - 1]]) * t;
    }
  }
  return g[ys[ys.length - 1]];
}

